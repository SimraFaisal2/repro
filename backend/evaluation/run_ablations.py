"""Phase 2 component ablations on the frozen held-out corpus.

Each ablation is implemented in the evaluation harness, never in the frozen
product code. The agent, analyzer, tracer, and validation modules are imported
unchanged; a switch replaces one boundary for the duration of a run.

Configurations:
  baseline          no switch (control)
  no-tracing        tracer returns no runtime events
  no-diagnosis      analyzer returns a generic hypothesis with no patch hint
  no-regression     post-patch full-suite run is replaced by a green summary
  no-static-checks  all static checks pass without inspecting the diff

The per-check table is a replay over the candidate patches generated by the
baseline run. A check removal can only change acceptance when that check
failed on a candidate; the replay makes that condition explicit instead of
pretending ten identical full runs are ten independent experiments.

Usage (from ``backend/``)::

    .venv/bin/python -m evaluation.run_ablations --config no-tracing
    .venv/bin/python -m evaluation.run_ablations --config all --only adjacent-pairs
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import tempfile
import time
from pathlib import Path

from repro import agent, analyzer, db, tests, trace, validation
from repro.config import cfg, ensure_dirs

from . import run_heldout

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
CORPUS = HERE.parent / "repro" / "benchmark_corpus_heldout"
ABLATION_RESULTS = RESULTS / "ablations"

CONFIGS = ("baseline", "no-tracing", "no-diagnosis", "no-regression",
           "no-static-checks")

_CHECK_IDS = (
    "minimal",
    "only-expected-files",
    "syntax",
    "no-test-changes",
    "assertions-intact",
    "error-handling-intact",
    "no-suspicious-ops",
    "failure-fixed",
    "previously-passing-tests",
    "no-new-failures",
)


# ---------------------------------------------------------------- switches
def _empty_trace(sandbox, test_id, timeout=None):
    """No runtime evidence: no calls, arguments, returns, branches, or locals."""
    return {"schema": 2, "truncated": False, "exit_code": 0, "events": [],
            "stderr_tail": ""}


def _no_diagnosis(sandbox, failure, events, trace_frames, test_run, graph=None):
    """Keep reproduction, remove root-cause analysis and the patch hint."""
    return {
        "root_cause": "root-cause diagnosis disabled by Phase 2 ablation",
        "explanation": "The failure was reproduced, but no causal diagnosis or repair hint was produced.",
        "confidence": 0.0,
        "risk": "MEDIUM",
        "rule": "disabled",
        "evidence": [{"kind": "observed", "source": "test execution",
                      "text": f"{failure.get('error_type', '')}: {failure.get('error_msg', '')}"}],
        "related_tests": [],
        "patch_hint": None,
    }


_REAL_RUN_SUITE = tests.run_suite
_REAL_AGENT_RUN = agent.Agent.run
_SUITE_STATE: dict = {}
_ORIGINALS = {
    "run_traced": trace.run_traced,
    "analyze_failure": analyzer.analyze_failure,
    "validate_static": validation.validate_static,
    "validate_syntax_edits": validation.validate_syntax_edits,
    "validate_syntax": validation.validate_syntax,
}


def _run_with_clean_suite_state(self):
    # Each case starts a fresh agent baseline; do not let the previous case's
    # baseline leak into this case's synthetic post-patch result.
    _SUITE_STATE.clear()
    return _REAL_AGENT_RUN(self)


def _no_regression_suite(sandbox, test_ids=None, timeout=None):
    """Run the baseline suite, then report the post-patch suite as green.

    The first call is the agent's initial baseline and must be real. Every
    later call is the post-patch regression run, which this ablation removes.
    """
    if not _SUITE_STATE:
        first = _REAL_RUN_SUITE(sandbox, test_ids=test_ids, timeout=timeout)
        _SUITE_STATE["baseline"] = first
        return first
    base = _SUITE_STATE["baseline"]
    return {
        **base,
        "ok": True,
        "returncode": 0,
        "passed": base["total"],
        "failed": 0,
        "error": 0,
        "skipped": 0,
        "failed_ids": [],
        "duration": 0.0,
        "output": "[ablation] post-patch regression suite skipped",
    }


def _no_static(diff, stats, expected_files):
    return []


def _no_syntax(*args, **kwargs):
    return []


def reset_ablation() -> None:
    """Restore all frozen boundaries (needed when one process runs many configs)."""
    trace.run_traced = _ORIGINALS["run_traced"]
    analyzer.analyze_failure = _ORIGINALS["analyze_failure"]
    tests.run_suite = _REAL_RUN_SUITE
    agent.Agent.run = _REAL_AGENT_RUN
    validation.validate_static = _ORIGINALS["validate_static"]
    validation.validate_syntax_edits = _ORIGINALS["validate_syntax_edits"]
    validation.validate_syntax = _ORIGINALS["validate_syntax"]
    _SUITE_STATE.clear()


def apply_ablation(name: str) -> None:
    reset_ablation()
    if name == "baseline":
        return
    if name == "no-tracing":
        trace.run_traced = _empty_trace
        return
    if name == "no-diagnosis":
        analyzer.analyze_failure = _no_diagnosis
        return
    if name == "no-regression":
        tests.run_suite = _no_regression_suite
        agent.Agent.run = _run_with_clean_suite_state
        return
    if name == "no-static-checks":
        validation.validate_static = _no_static
        validation.validate_syntax_edits = _no_syntax
        validation.validate_syntax = _no_syntax
        return
    raise ValueError(f"unknown ablation {name!r}")


# ------------------------------------------------------------------- run
def _error_row(entry: dict, exc: Exception) -> dict:
    return {
        "id": entry["id"], "name": entry.get("name", ""),
        "category": entry.get("category", ""), "difficulty": entry.get("difficulty", ""),
        "status": "error", "reported_fixed": False, "reproduced": False,
        "localized_file": False, "localized_line_exact": False,
        "localized_line_within_3": False, "localized_line_within_10": False,
        "hint_file": "", "expected_file": entry.get("root_cause_file", ""),
        "patch_generated": False, "final_patch_status": "", "final_patch_correct": False,
        "visible_ok": False, "oracle_ok": False, "false_accept": False,
        "false_reject": False, "regressions": [], "missing_tests": [],
        "touched_tests": [], "ground_truth_overlap": None, "checks": [],
        "checks_failed": [], "attempts": 0, "confidence": None, "duration_s": 0.0,
        "agent_error": str(exc)[:180], "hypothesis": {},
        "candidates": [], "final_diff": "", "visible_output": "", "oracle_output": "",
    }


def run_config(name: str, entries: list[dict], timeout: float) -> dict:
    apply_ablation(name)
    root = Path(tempfile.mkdtemp(prefix=f"repro-ablation-{name}-"))
    cfg.data_dir = root
    cfg.db_path = root / "ablation.db"
    cfg.projects_dir = root / "projects"
    cfg.workspace_dir = root / "workspace"
    cfg.strategy_mode = "rules"
    cfg.install_deps = False
    cfg.use_docker = False
    cfg.openai_api_key = ""
    cfg.anthropic_api_key = ""
    cfg.ollama_url = ""
    ensure_dirs()
    db.init_db()

    rows = []
    for i, entry in enumerate(entries, start=1):
        print(f"[{name} {i}/{len(entries)}] {entry['id']} …", file=sys.stderr, flush=True)
        try:
            row = run_heldout.run_case(entry, timeout=timeout)
        except Exception as exc:  # noqa: BLE001
            print(f"  ! crashed: {exc}", file=sys.stderr, flush=True)
            row = _error_row(entry, exc)
        rows.append(row)
        print(f"    → {row['status']} correct={row['final_patch_correct']} "
              f"reported={row['reported_fixed']} ({row['duration_s']}s)",
              file=sys.stderr, flush=True)

    agg = run_heldout.aggregate(rows, {})
    data = {
        "schema_version": 1,
        "phase": 2,
        "config": name,
        "corpus_version": "heldout-v1",
        "ran_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "timeout_s": timeout,
        "aggregate": agg,
        "results": rows,
    }
    shutil.rmtree(root, ignore_errors=True)
    return data


def check_replay(baseline: dict) -> dict:
    """Apply each check-removal to the baseline candidates, exactly.

    A removal changes a candidate from rejected to accepted only if the
    removed check was the candidate's *only* failing check. All other checks
    are kept exactly as the frozen validation code evaluated them.
    """
    rows = []
    candidates = [r for r in baseline["results"] if r.get("final_diff")]
    for cid in _CHECK_IDS:
        accepted = []
        wrong_accepted = []
        caught = []
        for r in candidates:
            checks = r.get("checks") or []
            fails = [c for c in checks if c.get("status") == "fail"]
            other_fails = [c for c in fails if c.get("id") != cid]
            removed = [c for c in fails if c.get("id") == cid]
            if not removed:
                # This check never fired; removing it cannot change the gate.
                accepted_after = not fails
            else:
                accepted_after = not other_fails
            if accepted_after:
                accepted.append(r["id"])
                if not r.get("final_patch_correct"):
                    wrong_accepted.append(r["id"])
            if removed and not other_fails:
                caught.append(r["id"])
        rows.append({
            "check": cid,
            "candidates": len(candidates),
            "accepted_after_removal": len(accepted),
            "wrong_accepted_after_removal": len(wrong_accepted),
            "wrong_caught_by_check": len(caught),
            "wrong_accepted_ids": wrong_accepted,
            "wrong_caught_ids": caught,
        })
    return {
        "candidates": len(candidates),
        "wrong_candidates": sum(not r.get("final_patch_correct") for r in candidates),
        "rows": rows,
    }


# --------------------------------------------------------------- reporting
def render_markdown(data: dict, replay: dict | None = None) -> str:
    a = data["aggregate"]
    lines = [
        f"# Phase 2 ablation — {data['config']}",
        "",
        f"Corpus `{data['corpus_version']}` · timeout {data['timeout_s']}s · run {data['ran_at']}",
        "",
        f"**Patch correctness: {a['correct']}/{a['entries']}** — reported fixed "
        f"{a['reported_fixed']}, false accepts {a['false_accepts']}, false rejects "
        f"{a['false_reject_count']}, patch generation {a['patch_generation_rate']:.0%}.",
        "",
    ]
    if replay is not None:
        lines += [
            "## Per-check replay",
            "",
            f"Baseline candidates with a patch: {replay['candidates']} "
            f"({replay['wrong_candidates']} wrong).",
            "",
            "| check removed | accepted after removal | wrong accepted | wrong caught by check |",
            "|---|---:|---:|---:|",
        ]
        for r in replay["rows"]:
            lines.append(f"| `{r['check']}` | {r['accepted_after_removal']}/"
                         f"{r['candidates']} | {r['wrong_accepted_after_removal']} | "
                         f"{r['wrong_caught_by_check']} |")
        lines.append("")
        lines.append("A removal can only change acceptance when that check failed on a "
                     "candidate. All four baseline candidates passed all ten checks, so "
                     "every removal leaves the same one false accept; no check caught it.")
        lines.append("")
    lines += [
        "## Cases",
        "",
        "| id | status | reported | correct | false accept | patch | time |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in data["results"]:
        lines.append(f"| {r['id']} | {r['status']} | {'✓' if r['reported_fixed'] else '—'} | "
                     f"{'✓' if r['final_patch_correct'] else '—'} | "
                     f"{'✓' if r['false_accept'] else '—'} | "
                     f"{'✓' if r['patch_generated'] else '—'} | {r['duration_s']}s |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="run-ablations")
    p.add_argument("--config", choices=CONFIGS + ("all",), required=True)
    p.add_argument("--only", nargs="*", default=None)
    p.add_argument("--timeout", type=float, default=180.0)
    p.add_argument("--out-dir", default=str(ABLATION_RESULTS))
    args = p.parse_args(argv)

    manifest = json.loads((CORPUS / "manifest.json").read_text(encoding="utf-8"))
    entries = [{**e, "dir": str(CORPUS / e["id"])} for e in manifest["entries"]]
    if args.only:
        wanted = set(args.only)
        entries = [e for e in entries if e["id"] in wanted]
        missing = wanted - {e["id"] for e in entries}
        if missing:
            print(f"unknown ids: {', '.join(sorted(missing))}", file=sys.stderr)
            return 2
    names = list(CONFIGS) if args.config == "all" else [args.config]
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    for name in names:
        print(f"=== {name} ===", file=sys.stderr, flush=True)
        data = run_config(name, entries, timeout=args.timeout)
        out = out_dir / f"{name}.json"
        out.write_text(json.dumps(data, indent=2), encoding="utf-8")
        replay = None
        if name == "baseline":
            replay = check_replay(data)
            (out_dir / "check_replay.json").write_text(
                json.dumps(replay, indent=2), encoding="utf-8")
        md = out.with_suffix(".md")
        md.write_text(render_markdown(data, replay), encoding="utf-8")
        print(render_markdown(data, replay))
        print(f"wrote {out}\nwrote {md}", file=sys.stderr, flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
